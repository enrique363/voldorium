"""Turns an Anime4K upscaling shader (mpv user shader, MIT licence, github.com/bloc97/Anime4K)
into port/m1/a4k_shaders.h, the passes render.c runs to enlarge 2D pictures (a4k_upscale).

Each pass keeps its GLSL body as is (the defines and hook()); the header lists the textures it
reads (//!BIND), the one it writes (//!SAVE) and whether it doubles the size (the final
depth-to-space pass, //!WIDTH ... 2 *). render.c adds what mpv provides around the body
(NAME_tex, NAME_pos, NAME_pt, NAME_size, NAME_texOff) and runs the passes in order.

Usage: python -I tools/a4k_shaders.py Anime4K_Upscale_CNN_x2_VL.glsl [out.h]
"""
import os
import sys

SC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def c_string(text):
    out = []
    for line in text.splitlines():
        out.append('\t"%s\\n"' % line.replace('\\', '\\\\').replace('"', '\\"'))
    return '\n'.join(out)


def main():
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(SC, 'port', 'm1', 'a4k_shaders.h')
    lines = open(src, encoding='utf-8').read().splitlines()
    licence = []
    for line in lines:
        if line.startswith('//!'):
            break
        if line.startswith('//') or (licence and not line.strip()):
            licence.append(line[2:].strip())
    while licence and not licence[-1]:
        licence.pop()
    passes = []
    cur = None
    for line in lines:
        if line.startswith('//!DESC'):
            cur = {'desc': line[8:].strip(), 'bind': [], 'save': None, 'x2': False, 'body': []}
            passes.append(cur)
        elif cur is None:
            continue
        elif line.startswith('//!BIND'):
            cur['bind'].append(line.split()[1])
        elif line.startswith('//!SAVE'):
            cur['save'] = line.split()[1]
        elif line.startswith('//!WIDTH'):
            cur['x2'] = line.split()[-1] == '*'
        elif line.startswith('//!'):
            continue
        elif line.strip() or cur['body']:
            cur['body'].append(line)
    for p in passes:
        assert p['save'] and p['bind'] and len(p['bind']) <= 16, p['desc']
    w = open(out, 'w', newline='\n')
    w.write('/* Generated by tools/a4k_shaders.py from %s: do not edit.\n *\n' % os.path.basename(src))
    w.write(' * Anime4K (github.com/bloc97/Anime4K), used under its licence:\n *\n')
    for line in licence:
        w.write((' * ' + line).rstrip() + '\n')
    w.write(' */\n')
    w.write('typedef struct\n{\n\tconst char *desc, *save;\n\tint nbind, x2;\n\tconst char *bind[16];\n\tconst char *body;\n} A4kPass;\n\n')
    w.write('static const A4kPass a4k_passes[] = {\n')
    for p in passes:
        w.write('\t{ "%s", "%s", %d, %d, { %s },\n' % (p['desc'], p['save'], len(p['bind']), int(p['x2']),
                                                      ', '.join('"%s"' % b for b in p['bind'])))
        w.write(c_string('\n'.join(p['body'])) + ' },\n')
    w.write('};\n')
    w.close()
    print('%s: %d passes' % (out, len(passes)))


if __name__ == '__main__':
    main()
